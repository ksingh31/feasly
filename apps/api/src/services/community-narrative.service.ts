/**
 * Monthly community narratives (#759, owner decision 2026-11-15).
 *
 * The LLM writes ONE neighbourhood narrative per community per month; every
 * report in that community reuses the stored text (one DB read, no LLM
 * call per estimate). This service owns:
 *
 * - `runScheduledTick()` — the daily timer tick. On the run day (default:
 *   last day of the month) it generates next month's narrative for every
 *   community in `community_stats`; the next `retryDays` ticks retry the
 *   failures. Idempotent (communities that already succeeded for the period
 *   are skipped) and resumable (one community failing never stops the
 *   rest). If failures remain on the last retry day, ONE ops alert fires.
 *   Every tick also finishes rows an admin marked 'stale'.
 * - `regenerate()` — admin "Regenerate now" for one community or all.
 * - `listStatus()` — each community's latest period, status, and date.
 * - `findServable()` — the stored narrative a report should show: the
 *   newest period with text, so a failed month keeps last month's.
 *
 * Hard rule: the LLM writes wording only. The prompt carries community
 * stats (the one sanctioned $-figure is the City-assessed average), and
 * `validateCommunityNarrative()` rejects any other figure, with one repair
 * retry — the same guard + retry as the old per-estimate worker.
 *
 * Telemetry: one `community_narrative.run` JSON log line per tick/admin
 * request with attempted/succeeded/failed counts (App Insights traces).
 * Never logs narrative text or prompts.
 */
import {
  buildCommunityNarrativePrompt,
  ensureNarrativeFooter,
  validateCommunityNarrative,
  type CommunityFacts,
} from '@feasly/cost-engine';
import { ErrorCodes, HttpError } from '../middleware/errors';
import { periodOf, runWindowFor } from '../lib/narrative-period';
import { sanitizeErrorMessage } from '../lib/sanitize-error';
import type {
  CommunityNarrativeRecord,
  CommunityNarrativeStatus,
  CommunityNarrativeStore,
  CoveredCommunity,
} from './community-narrative.store';
import { isSyntheticNarrative } from './narrative/narrative.types';
import type { NarrativeProvider } from './narrative/narrative.types';
import type { OpsAlertsService } from './ops-alerts.service';

export interface CommunityNarrativeRunResult {
  /** 'timer' tick or 'admin' regenerate. */
  readonly trigger: 'timer' | 'admin';
  /** Period generated by the scheduled run; null outside the run window. */
  readonly period: string | null;
  readonly attempted: number;
  readonly succeeded: number;
  readonly failed: number;
  /** Targets left for a later tick (cost guard / admin time budget). */
  readonly deferred: number;
  /** True when the final-retry ops alert was raised this tick. */
  readonly alerted: boolean;
}

export interface CommunityNarrativeStatusEntry {
  readonly communitySlug: string;
  readonly communityName: string;
  /** Newest period with a row; null when never attempted. */
  readonly period: string | null;
  readonly status: CommunityNarrativeStatus | 'missing';
  /** When the stored text was generated; null when there is none. */
  readonly generatedAt: Date | null;
  readonly attempts: number;
  readonly lastError: string | null;
}

/** What a report shows for a community. */
export interface ServableCommunityNarrative {
  readonly communitySlug: string;
  readonly period: string;
  readonly narrative: string;
  readonly generatedAt: Date;
}

export interface CommunityNarrativeService {
  runScheduledTick(): Promise<CommunityNarrativeRunResult>;
  /**
   * Regenerate now. With a slug: that community, synchronously. Without:
   * every covered community is marked stale and as many as the time
   * budget allows are regenerated; the next daily tick finishes the rest.
   * Throws 404 for an unknown community, 409 when the feature is disabled.
   */
  regenerate(target: { readonly communitySlug?: string }): Promise<CommunityNarrativeRunResult>;
  listStatus(): Promise<readonly CommunityNarrativeStatusEntry[]>;
  /** One DB read; never calls the LLM. Null when nothing is stored. */
  findServable(communitySlug: string): Promise<ServableCommunityNarrative | null>;
}

export interface CommunityNarrativeServiceDeps {
  readonly store: CommunityNarrativeStore;
  readonly provider: NarrativeProvider;
  readonly opsAlerts: Pick<OpsAlertsService, 'notifyFailure'>;
  readonly config: {
    readonly enabled: boolean;
    readonly runDay: 'last' | number;
    readonly retryDays: number;
    readonly promptVersion: string;
    readonly maxPerRun: number;
    readonly adminBudgetMs: number;
  };
  readonly clock?: () => Date;
  /** Telemetry sink (default: one JSON console.info line). */
  readonly logEvent?: (event: Record<string, unknown>) => void;
}

/** Aggregate vintage label for the prompt, e.g. "September 2026". */
function vintageLabel(d: Date): string {
  const month = d.toLocaleString('en-US', { month: 'long', timeZone: 'UTC' });
  return `${month} ${d.getUTCFullYear()}`;
}

function factsFor(community: CoveredCommunity): CommunityFacts {
  return {
    community: community.name,
    avgSingleFamilyAssessedValue: community.avgAssessedValue,
    assessedHomeCount: community.assessmentCount,
    avgLotSqft: community.avgLotSqft,
    dataVintage: vintageLabel(community.refreshedAt),
  };
}

interface Target {
  readonly community: CoveredCommunity;
  readonly period: string;
}

export function createCommunityNarrativeService(
  deps: CommunityNarrativeServiceDeps,
): CommunityNarrativeService {
  const { store, provider, config } = deps;
  const clock = deps.clock ?? (() => new Date());
  const logEvent =
    deps.logEvent ??
    ((event: Record<string, unknown>) => console.info(JSON.stringify(event)));

  /**
   * Generate + validate + store one community narrative. Returns true on
   * success. Never throws for generation problems — a failure is recorded
   * on the row so the rest of the run continues.
   */
  async function generateOne(target: Target): Promise<boolean> {
    const { community, period } = target;
    const facts = factsFor(community);
    const prompt = buildCommunityNarrativePrompt(facts);
    let error = 'unknown failure';
    try {
      // First sample + one repair retry on a validation failure. Provider
      // errors are not retried here: the provider already walks its model
      // chain, and the next tick retries the community.
      for (let attempt = 0; attempt < 2; attempt++) {
        const result = await provider.generate(prompt);
        if (provider.synthetic || isSyntheticNarrative(result.text)) {
          error = 'synthetic provider output (no LLM configured)';
          break;
        }
        const text = ensureNarrativeFooter(result.text);
        const validation = validateCommunityNarrative(text, facts);
        if (validation.ok) {
          await store.recordSuccess({
            communitySlug: community.slug,
            period,
            narrative: text,
            model: result.model,
            promptVersion: config.promptVersion,
            at: clock(),
          });
          return true;
        }
        error = `LLM output failed validation: ${validation.violations.join('; ')}`;
      }
    } catch (cause) {
      error = sanitizeErrorMessage(cause);
    }
    try {
      await store.recordFailure({
        communitySlug: community.slug,
        period,
        promptVersion: config.promptVersion,
        error: error.slice(0, 500),
        at: clock(),
      });
    } catch (storeError) {
      console.error(
        JSON.stringify({
          event: 'community_narrative.record_failure_failed',
          communitySlug: community.slug,
          error: sanitizeErrorMessage(storeError),
        }),
      );
    }
    return false;
  }

  async function processTargets(
    targets: readonly Target[],
    deadline: number | null,
  ): Promise<{ attempted: number; succeeded: number; failed: number; deferred: number }> {
    const capped = targets.slice(0, config.maxPerRun);
    let attempted = 0;
    let succeeded = 0;
    for (const target of capped) {
      if (deadline !== null && Date.now() >= deadline) break;
      attempted++;
      if (await generateOne(target)) succeeded++;
    }
    return {
      attempted,
      succeeded,
      failed: attempted - succeeded,
      deferred: targets.length - attempted,
    };
  }

  /** Stale rows (admin requests) whose community is still covered. */
  async function staleTargets(
    covered: ReadonlyMap<string, CoveredCommunity>,
  ): Promise<Target[]> {
    const stale = await store.listStale();
    return stale.flatMap((row) => {
      const community = covered.get(row.communitySlug);
      return community ? [{ community, period: row.period }] : [];
    });
  }

  function emit(result: CommunityNarrativeRunResult, extra: Record<string, unknown> = {}): void {
    logEvent({ event: 'community_narrative.run', ...result, ...extra });
  }

  /** Period an admin regenerate writes: the one being (or about to be) served. */
  function adminPeriod(now: Date): string {
    return runWindowFor(now, config.runDay, config.retryDays)?.period ?? periodOf(now);
  }

  return {
    async runScheduledTick(): Promise<CommunityNarrativeRunResult> {
      const empty: CommunityNarrativeRunResult = {
        trigger: 'timer',
        period: null,
        attempted: 0,
        succeeded: 0,
        failed: 0,
        deferred: 0,
        alerted: false,
      };
      if (!config.enabled) {
        emit(empty, { disabled: true });
        return empty;
      }
      const now = clock();
      const window = runWindowFor(now, config.runDay, config.retryDays);
      const coveredList = await store.listCoveredCommunities();
      const covered = new Map(coveredList.map((c) => [c.slug, c]));

      const targets = new Map<string, Target>();
      if (window) {
        const done = new Set(
          (await store.listForPeriod(window.period))
            .filter((row) => row.status === 'succeeded')
            .map((row) => row.communitySlug),
        );
        for (const community of coveredList) {
          if (!done.has(community.slug)) {
            targets.set(`${community.slug}|${window.period}`, {
              community,
              period: window.period,
            });
          }
        }
      }
      for (const target of await staleTargets(covered)) {
        targets.set(`${target.community.slug}|${target.period}`, target);
      }

      const counts = await processTargets([...targets.values()], null);

      let alerted = false;
      if (window && window.daysSinceRunDay >= config.retryDays && !provider.synthetic) {
        const succeededForPeriod = new Set(
          (await store.listForPeriod(window.period))
            .filter((row) => row.status === 'succeeded')
            .map((row) => row.communitySlug),
        );
        const outstanding = coveredList.filter((c) => !succeededForPeriod.has(c.slug)).length;
        if (outstanding > 0) {
          try {
            await deps.opsAlerts.notifyFailure('narrative_worker_failed', {
              consecutiveFailures: config.retryDays + 1,
              firstFailureAt: new Date(now.getTime() - window.daysSinceRunDay * 86_400_000),
            });
            alerted = true;
          } catch (alertError) {
            console.error(
              JSON.stringify({
                event: 'community_narrative.alert_failed',
                error: sanitizeErrorMessage(alertError),
              }),
            );
          }
        }
      }

      const result: CommunityNarrativeRunResult = {
        trigger: 'timer',
        period: window?.period ?? null,
        ...counts,
        alerted,
      };
      emit(result, { daysSinceRunDay: window?.daysSinceRunDay ?? null });
      return result;
    },

    async regenerate(target): Promise<CommunityNarrativeRunResult> {
      if (!config.enabled) {
        throw new HttpError(
          409,
          ErrorCodes.CONFLICT,
          'Community narrative generation is turned off (COMMUNITY_NARRATIVE_ENABLED=false).',
          false,
        );
      }
      const now = clock();
      const period = adminPeriod(now);
      let targets: Target[];
      if (target.communitySlug !== undefined) {
        const community = await store.getCoveredCommunity(target.communitySlug);
        if (!community) {
          throw new HttpError(404, ErrorCodes.COMMUNITY_NOT_FOUND, 'Unknown community.', false);
        }
        targets = [{ community, period }];
      } else {
        const coveredList = await store.listCoveredCommunities();
        // Mark first, so whatever the time budget leaves undone is picked
        // up by the next daily tick.
        await store.markStale({
          communitySlugs: coveredList.map((c) => c.slug),
          period,
          promptVersion: config.promptVersion,
          at: now,
        });
        targets = coveredList.map((community) => ({ community, period }));
      }
      const deadline = target.communitySlug !== undefined ? null : Date.now() + config.adminBudgetMs;
      const counts = await processTargets(targets, deadline);
      const result: CommunityNarrativeRunResult = {
        trigger: 'admin',
        period,
        ...counts,
        alerted: false,
      };
      emit(result, { scope: target.communitySlug !== undefined ? 'one' : 'all' });
      return result;
    },

    async listStatus(): Promise<readonly CommunityNarrativeStatusEntry[]> {
      const [coveredList, latest] = await Promise.all([
        store.listCoveredCommunities(),
        store.listLatestPerCommunity(),
      ]);
      const bySlug = new Map<string, CommunityNarrativeRecord>(
        latest.map((row) => [row.communitySlug, row]),
      );
      return coveredList.map((community) => {
        const row = bySlug.get(community.slug);
        return {
          communitySlug: community.slug,
          communityName: community.name,
          period: row?.period ?? null,
          status: row?.status ?? 'missing',
          generatedAt: row?.generatedAt ?? null,
          attempts: row?.attempts ?? 0,
          lastError: row?.lastError ?? null,
        };
      });
    },

    async findServable(communitySlug): Promise<ServableCommunityNarrative | null> {
      const row = await store.findServable(communitySlug);
      if (!row?.narrative || !row.generatedAt || isSyntheticNarrative(row.narrative)) {
        return null;
      }
      return {
        communitySlug: row.communitySlug,
        period: row.period,
        narrative: row.narrative,
        generatedAt: row.generatedAt,
      };
    },
  };
}
