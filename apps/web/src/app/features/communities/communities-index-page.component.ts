import { Component, inject, OnInit } from '@angular/core';
import { RouterLink } from '@angular/router';
import type { CommunityGroup, CommunityIndexEntry, CommunityIndexFile } from '@feasly/contracts';
import { ConfigService } from '../../core/config';
import { SeoService } from '../../core/seo';
import { buildItemListSchema } from '../../core/seo/jsonld-schemas';
import { SiteFooterComponent, SiteNavComponent } from '../../shared/components';
import { formatRoundedCad } from '../../shared/utils/money';
import indexData from '../../../content/data/community-index.json';
import { toDisplayName } from './community-names';

/** One index section: a heading plus its community cards. */
interface CommunitySection {
  readonly id: CommunityGroup;
  readonly heading: string;
  readonly body: string;
  readonly communities: readonly CommunityIndexEntry[];
}

/** Section order (#690): established/infill communities first. */
const GROUP_ORDER: readonly CommunityGroup[] = ['established', 'newer'];

/**
 * Community index (SEO-05): prerendered `/communities/` listing every
 * Calgary community guide. Each card links to its community page
 * (`/communities/{slug}`); the page is the single crawl hub so no
 * community guide is orphaned.
 *
 * Two card variants: build-guide communities link to the cost guide,
 * profile communities (condo/apartment-dominated) link to the
 * property-values profile. The CTA copy says which is which — never
 * promising a cost guide that doesn't exist.
 *
 * #690: cards are grouped into "established" (inner-city and older
 * communities, where most infill happens — shown first) and "newer"
 * communities, from the City's community-structure field.
 *
 * Data: `community-index.json` (minimal per-community entries, generated by
 * `scripts/build-community-pages.ts`) is a static import — bundled at build
 * time, so cards render at prerender with no runtime fetch.
 *
 * U1 (2026-09-28): cards no longer show a "New build from $X" teaser. The
 * build-cost side of the ranges file is not community-specific, so
 * repeating it looked like placeholder data. Each card shows the
 * community's own average assessed value instead; per-community build
 * costs live on the guide pages.
 */
@Component({
  selector: 'app-communities-index-page',
  standalone: true,
  imports: [RouterLink, SiteFooterComponent, SiteNavComponent],
  templateUrl: './communities-index-page.component.html',
  styleUrl: './communities-index-page.component.scss',
})
export class CommunitiesIndexPageComponent implements OnInit {
  private readonly seo = inject(SeoService);
  private readonly config = inject(ConfigService);

  /** Community index copy (config-owned, no hardcoded literals). */
  protected readonly indexCopy = this.config.get('copy').marketing.communities;

  /**
   * Sections in display order, empty ones dropped. Within a section
   * (consumer review S8): single-family build-guide communities first,
   * condo/apartment-dominated profile communities last, each alphabetical
   * by display name.
   */
  protected readonly sections: readonly CommunitySection[] = GROUP_ORDER.map((id) => ({
    id,
    heading: this.indexCopy.groups[id].heading,
    body: this.indexCopy.groups[id].body,
    communities: (indexData as CommunityIndexFile).communities
      .filter((c) => (c.group ?? 'newer') === id)
      .sort(
        (a, b) =>
          Number(this.isProfile(a)) - Number(this.isProfile(b)) ||
          toDisplayName(a.name).localeCompare(toDisplayName(b.name), 'en-CA'),
      ),
  })).filter((s) => s.communities.length > 0);

  /** Every card, in display order. */
  protected readonly communities: readonly CommunityIndexEntry[] = this.sections.flatMap((s) => s.communities);

  ngOnInit(): void {
    this.seo.setForRoute('communities');
    // SEO: ItemList of every community guide — crawlers discover every
    // guide from the hub's structured data, not just the anchor links.
    const siteUrl = this.seo.getSiteUrl();
    this.seo.setJsonLd(
      buildItemListSchema(
        `${siteUrl}/communities/`,
        this.communities.map((c) => ({
          name: `${toDisplayName(c.name)}, Calgary`,
          url: `${siteUrl}/communities/${c.slug}/`,
        })),
      ),
    );
  }

  /** Formatted average assessed value, rounded to $1,000 (#504), e.g. "$607,000". */
  assessedValue(community: CommunityIndexEntry): string {
    return formatRoundedCad(community.avgAssessedValue, this.config.get('limits').estimateRoundingStep);
  }

  /** Router link to the community's page (guide or profile). */
  communityLink(community: CommunityIndexEntry): string {
    return `/communities/${community.slug}`;
  }

  /** Whether the community gets the property-profile page instead of the cost guide. */
  isProfile(community: CommunityIndexEntry): boolean {
    return community.type === 'profile';
  }

  /** Card CTA: honest about which page the card leads to. */
  cardCta(community: CommunityIndexEntry): string {
    return this.isProfile(community) ? 'View community profile →' : 'View cost guide →';
  }
}
