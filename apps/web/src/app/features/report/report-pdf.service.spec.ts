import { TestBed } from '@angular/core/testing';
import { describe, expect, it } from 'vitest';
import type { CostRow } from '@feasly/contracts';
import { mockReport } from '../../core/api/mock-data';
import { ReportPdfService, sanitizePdfText, type ReportPdfInput } from './report-pdf.service';

/**
 * ReportPdfService renders the verified snapshot to a real PDF via jsPDF
 * (lazy-loaded). The service owns layout; the component owns the download
 * plumbing and UI states.
 */
describe('ReportPdfService', () => {
  function input(overrides: Partial<ReportPdfInput> = {}): ReportPdfInput {
    const snapshot = mockReport(
      'estimate-1',
      'lead-1',
      { sqft: 2200, tier: 'premium', garage: 'double', basement: 'unfinished' },
      'Dollar figures are calculated deterministically from our cost model — not generated by AI.',
    );
    return {
      snapshot,
      address: '2631 63 Ave SW, Calgary, AB',
      title: 'New-build cost report',
      preparedLine: 'Prepared September 27, 2026',
      versionLine: 'Report version 3',
      steps: [
        { title: 'Meet your matched builder', body: 'We can connect you.' },
        { title: 'Refine your project brief', body: 'Lock in must-haves.' },
      ],
      disclaimer: 'Dollar figures are calculated deterministically from our cost model — not generated by AI.',
      uncalibratedNote: 'Uncalibrated planning figures.',
      ...overrides,
    };
  }

  it('generates a non-empty PDF blob with the PDF magic bytes', async () => {
    const service = TestBed.inject(ReportPdfService);
    const blob = await service.generate(input());
    expect(blob).toBeInstanceOf(Blob);
    expect(blob.type).toBe('application/pdf');
    expect(blob.size).toBeGreaterThan(1000);
    expect(await blob.slice(0, 5).text()).toBe('%PDF-');
  });

  it('embeds the address, version, and formatted figures in the PDF content', async () => {
    const service = TestBed.inject(ReportPdfService);
    const blob = await service.generate(input());
    // jsPDF encodes body text as literal WinAnsi strings, so distinctive
    // content is searchable in the raw output.
    const raw = await blob.text();
    expect(raw).toContain('2631 63 Ave SW, Calgary, AB');
    expect(raw).toContain('Report version 3');
    expect(raw).toContain('Feasly');
  });

  it('renders the honest empty-narrative fallback instead of inventing text', async () => {
    const service = TestBed.inject(ReportPdfService);
    const empty = input();
    const blob = await service.generate({
      ...empty,
      snapshot: { ...empty.snapshot, narrative: '   ' },
    });
    const raw = await blob.text();
    expect(raw).toContain('the figures above are the complete estimate');
  });

  it('includes the coverage framing and the landscaping-only exclusion', async () => {
    const service = TestBed.inject(ReportPdfService);
    const blob = await service.generate(input());
    const raw = await blob.text();
    // jsPDF WinAnsi-encodes body text; assert on ASCII-safe substrings.
    expect(raw).toContain('60+ line items');
    expect(raw).toContain('not in this estimate');
    // Landscaping is the only exclusion (Karan 2026-09-28).
    expect(raw).toContain('Landscaping');
    expect(raw).not.toContain('Demolition of any existing home');
    expect(raw).not.toContain('Financing costs');
  });

  it('omits the new-build exclusions on a renovation snapshot', async () => {
    const service = TestBed.inject(ReportPdfService);
    const renoInput = input();
    const blob = await service.generate({
      ...renoInput,
      title: 'Renovation estimate',
      snapshot: { ...renoInput.snapshot, projectType: 'renovation' as const },
    });
    const raw = await blob.text();
    // New-build coverage framing must not leak onto reno PDFs.
    expect(raw).not.toContain('60+ line items');
    expect(raw).not.toContain('not in this estimate');
    expect(raw).not.toContain('Demolition of any existing home');
  });

  it('strips unencodable characters so jsPDF stays in WinAnsi (QA bug: feasly-estimate-1.pdf narrative clipped)', async () => {
    const service = TestBed.inject(ReportPdfService);
    const dirty = input();
    const blob = await service.generate({
      ...dirty,
      snapshot: {
        ...dirty.snapshot,
        // The real triggers (jsPDF 4.2.1 trigger matrix): U+200B/U+2028
        // (which LLMs emit) flip the whole line to UTF-16BE
        // (NUL-interleaved) and the line renders ~2x too wide, clipped at
        // the page edge. C0 controls like \x11 have no WinAnsi glyph either.
        narrative:
          'Sunalta is a well\u200b-established\u200b\u2028inner city neighbourhood.\x11\x0BFees are calculated deterministically — no surprises…',
      },
    });
    const raw = await blob.text();
    // No UTF-16BE (NUL-interleaved) text anywhere in the output.
    expect(raw).not.toContain('\x00');
    // Words intact after the unencodable chars are stripped; legitimate
    // WinAnsi-mapped punctuation (— …) survives.
    expect(raw).toContain('Sunalta is a well-establishedinner city neighbourhood.');
    expect(raw).toContain('Fees are calculated deterministically');
    expect(raw).toContain('no surprises');
  });

  it('renders the same three cost buckets as the report page, land excluded', async () => {
    const service = TestBed.inject(ReportPdfService);
    // The 10 raw engine rows of a real snapshot, including the land row that
    // the PDF used to dump verbatim (QA bug: breakdown did not match the page).
    const rows: CostRow[] = [
      { key: 'land', label: 'Land (assessed value)', range: { low: 4930000, base: 4930000, high: 4930000 } },
      { key: 'hard.framing', label: 'Framing & structure', range: { low: 80000, base: 90000, high: 100000 } },
      { key: 'hard.foundation', label: 'Foundation', range: { low: 59000, base: 66000, high: 73000 } },
      { key: 'hard.envelope', label: 'Envelope (roof, siding, windows)', range: { low: 65000, base: 72000, high: 79000 } },
      { key: 'hard.sitePrep', label: 'Site preparation & excavation', range: { low: 41000, base: 46000, high: 51000 } },
      { key: 'hard.finishes', label: 'Interior finishes', range: { low: 108000, base: 120000, high: 132000 } },
      { key: 'hard.mep', label: 'Mechanical, electrical & plumbing', range: { low: 61000, base: 68000, high: 75000 } },
      { key: 'soft.design', label: 'Design & engineering', range: { low: 23000, base: 26000, high: 29000 } },
      { key: 'soft.permits', label: 'Permits & fees', range: { low: 5000, base: 7000, high: 9000 } },
      { key: 'contingency', label: 'Contingency', range: { low: 52000, base: 52803, high: 52803 } },
    ];
    const bucketed = input();
    const blob = await service.generate({
      ...bucketed,
      snapshot: { ...bucketed.snapshot, rows },
    });
    // jsPDF escapes parens in literal strings (\( \)); normalize so label
    // assertions read like the on-screen text.
    const raw = (await blob.text()).replace(/\\\(/g, '(').replace(/\\\)/g, ')');
    // Exactly the three bucket labels the report page renders.
    expect(raw).toContain('Structure & exterior');
    expect(raw).toContain('Interior & home systems');
    expect(raw).toContain('Design, permits & contingency');
    // Each bucket's base figure, summed from the raw rows (land excluded).
    expect(raw).toContain('$274,000'); // 90k+66k+72k+46k
    expect(raw).toContain('$188,000'); // 120k+68k
    expect(raw).toContain('$85,803'); // 26k+7k+52,803
    // No per-row dump, and no land breakdown row duplicating the summary's.
    expect(raw).not.toContain('Land (assessed value)');
    expect(raw).not.toContain('Framing & structure');
    expect(raw).not.toContain('Interior finishes');
    // Land still has its own figure in the summary section.
    expect(raw).toContain('Land (City assessed value)');
  });

  it('never draws text past the right margin, even with adversarial input', async () => {
    const service = TestBed.inject(ReportPdfService);
    const nasty = input();
    const blob = await service.generate({
      ...nasty,
      address: 'A'.repeat(120) + ' 1234 99 Street NW, Calgary, AB',
      snapshot: {
        ...nasty.snapshot,
        narrative:
          'Well\x00formed\x11text\u200bwith\u2028zero-width\x7Fchars and a supercalifragilisticexpialidociousantidisestablishmentarianism token ' +
          'plus emoji 😀 and curly “quotes” — em dashes… repeated '.repeat(6),
      },
      steps: [
        {
          title: 'A very long step title that should wrap ' + 'x'.repeat(80),
          body: 'Body with\x02control chars andaverylongunbrokenstring'.repeat(4) + ' end.',
        },
      ],
      disclaimer: 'Disclaimer '.repeat(40) + '\x00\x11 tail.',
    });

    // Byte-accurate latin1 decode so WinAnsi bytes stay 1:1.
    const bytes = new Uint8Array(await blob.arrayBuffer());
    let raw = '';
    const CHUNK = 0x8000;
    for (let i = 0; i < bytes.length; i += CHUNK) {
      raw += String.fromCharCode.apply(null, bytes.subarray(i, i + CHUNK) as unknown as number[]);
    }

    // Map font refs (F1/F2/...) to helvetica bold or not.
    const fontBold = new Map<string, boolean>();
    const objBold = new Map<string, boolean>();
    const fontObjRe = /(\d+) 0 obj\s*<<\s*\/Type\s*\/Font\s*\/BaseFont\s*\/([A-Za-z-]+)/g;
    let fontMatch: RegExpExecArray | null;
    while ((fontMatch = fontObjRe.exec(raw)) !== null) {
      objBold.set(fontMatch[1], fontMatch[2].toLowerCase().includes('bold'));
    }
    const resRe = /\/Font\s*<<([^>]*)>>/g;
    let resMatch: RegExpExecArray | null;
    while ((resMatch = resRe.exec(raw)) !== null) {
      const refRe = /\/F(\d+)\s+(\d+) 0 R/g;
      let refMatch: RegExpExecArray | null;
      while ((refMatch = refRe.exec(resMatch[1])) !== null) {
        fontBold.set(`F${refMatch[1]}`, objBold.get(refMatch[2]) ?? false);
      }
    }

    const { jsPDF } = await import('jspdf');
    const measurer = new jsPDF({ unit: 'pt', format: 'letter' });
    const margin = 48;
    const limit = 612 - margin; // letter width minus right margin

    const decodeLiteral = (s: string): string =>
      s.replace(/\\(\d{3}|.)/g, (_m, code: string) =>
        /^\d{3}$/.test(code) ? String.fromCharCode(parseInt(code, 8)) : code,
      );

    const streamRe = /stream\r?\n([\s\S]*?)endstream/g;
    let streamMatch: RegExpExecArray | null;
    let checked = 0;
    const violations: string[] = [];
    const tokRe =
      /(-?\d+(?:\.\d*)?)\s+(-?\d+(?:\.\d*)?)\s+Td|\/F(\d+)\s+(-?\d+(?:\.\d*)?)\s+Tf|(\((?:\\.|[^\\()])*\))(\s*Tj)|\[((?:\((?:\\.|[^\\()])*\)|[\s\d.\-]+)*)\](\s*TJ)|T\*/g;
    while ((streamMatch = streamRe.exec(raw)) !== null) {
      const stream = streamMatch[1];
      let x: number | null = null;
      let size = 10;
      let bold = false;
      let tok: RegExpExecArray | null;
      tokRe.lastIndex = 0;
      while ((tok = tokRe.exec(stream)) !== null) {
        if (tok[1] !== undefined) {
          x = parseFloat(tok[1]);
        } else if (tok[3] !== undefined) {
          bold = fontBold.get(`F${tok[3]}`) ?? false;
          size = parseFloat(tok[4]);
        } else if (tok[5] !== undefined) {
          // (...) Tj
          if (x === null) continue;
          const str = decodeLiteral(tok[5].slice(1, -1));
          measurer.setFont('helvetica', bold ? 'bold' : 'normal');
          measurer.setFontSize(size);
          const w = measurer.getTextWidth(str);
          checked++;
          if (x + w > limit + 1) {
            violations.push(`"${str.slice(0, 40)}…" at x=${x.toFixed(1)} width=${w.toFixed(1)}`);
          }
        } else if (tok[7] !== undefined) {
          // [...] TJ
          if (x === null) continue;
          const inner = tok[7];
          let w = 0;
          const partRe = /\((?:\\.|[^\\()])*\)|-?\d+(?:\.\d+)?/g;
          let part: RegExpExecArray | null;
          measurer.setFont('helvetica', bold ? 'bold' : 'normal');
          measurer.setFontSize(size);
          while ((part = partRe.exec(inner)) !== null) {
            const p = part[0];
            if (p.startsWith('(')) {
              w += measurer.getTextWidth(decodeLiteral(p.slice(1, -1)));
            } else {
              w -= (parseFloat(p) / 1000) * size;
            }
          }
          checked++;
          if (x + w > limit + 1) {
            violations.push(`TJ array at x=${x.toFixed(1)} width=${w.toFixed(1)}`);
          }
        }
        // T* keeps x — nothing to do.
      }
    }
    expect(checked).toBeGreaterThan(0);
    expect(violations).toEqual([]);
  });
});

describe('sanitizePdfText', () => {
  it('strips C0 controls, DEL and C1 controls but preserves newlines and tabs', () => {
    expect(sanitizePdfText('a\x11b\x00c\x7Fde')).toBe('abcde');
    expect(sanitizePdfText('line1\nline2\tline3')).toBe('line1\nline2\tline3');
    expect(sanitizePdfText('plain text')).toBe('plain text');
  });

  it('strips unmapped >U+00FF chars that would flip jsPDF to UTF-16BE, keeps WinAnsi-mapped punctuation', () => {
    // U+200B / U+2028 (LLM favourites) flip the whole line to UTF-16BE.
    expect(sanitizePdfText('a\u200bb\u2028c')).toBe('abc');
    // cp1252-mapped punctuation renders fine in WinAnsi — keep it.
    expect(sanitizePdfText('em—dash ‘quote’ “double” ellipsis…')).toBe(
      'em—dash ‘quote’ “double” ellipsis…',
    );
    // Surrogate-pair emoji would also flip the line — drop it.
    expect(sanitizePdfText('hi 😀 bye')).toBe('hi  bye');
  });
});
