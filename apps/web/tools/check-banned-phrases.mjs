#!/usr/bin/env node
/**
 * Banned-phrase + disclaimer check (HRD-05, acceptance criterion 3).
 *
 * Two jobs:
 *
 * 1. BANNED PHRASES — fails (exit 1) when user-facing copy contains:
 *      guarantee | ± | accurate within/to | market value | appraisal
 *    …outside explicitly allowlisted disclaimer forms ("not guarantees",
 *    "not an appraisal", "not market value", …). Only user-facing strings
 *    are scanned: HTML templates (comments stripped) and string literals
 *    extracted from the copy-source .ts files. Code comments are never
 *    scanned — "the type guarantees no leaks" is not a user-facing claim.
 *
 * 2. DISCLAIMER PRESENCE — fails when the approved deterministic-math
 *    disclaimer is missing from any of the four surfaces:
 *      report (web report page) · print (same page, must print) ·
 *      API (EstimateResponse.disclaimer) · MCP (every tool description in
 *    packages/mcp/src/tools.ts carries ESTIMATE_DISCLAIMER — #765; the
 *    check notes a skip only when the MCP package is absent).
 *
 * 3. SINGLE "UNLOCK" (issue #506) — "Unlock" appears in user-facing copy
 *    exactly once: the preview CTA (copy.report.unlockCta).
 *
 * Proven to bite by apps/web/tools/check-banned-phrases.spec.ts (vitest).
 *
 * Usage: node apps/web/tools/check-banned-phrases.mjs (paths resolve from
 * the script location, so any cwd works).
 */
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { dirname, join, relative, extname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const TOOLS_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = join(TOOLS_DIR, '..', '..', '..'); // repo root

/** The approved disclaimer, verbatim (must match ESTIMATE_DISCLAIMER). */
export const APPROVED_DISCLAIMER =
  'Dollar figures are calculated deterministically from our cost model — not generated by AI.';

// ── Banned patterns ──────────────────────────────────────────────────────
// Each entry: regex + a "negation lookbehind" — when the 40 chars before the
// match contain one of these negations, the hit is a disclaimer, not a claim.
export const BANNED_PATTERNS = [
  { name: 'guarantee', re: /guarantee/i, negations: ['not', 'no', 'never', 'without'] },
  { name: '±', re: /±/, negations: [] },
  { name: 'accurate within/to', re: /accurate\s+(within|to)/i, negations: [] },
  { name: 'market value', re: /market value/i, negations: ['not'] },
  { name: 'appraisal', re: /appraisal/i, negations: ['not', 'no'] },
  // #878 (owner decision 2026-11-15): direct-site leads go to Feasly's
  // builder partner(s), who pay a referral commission. Claims of neutral
  // matching contradict that disclosure, so they are banned outright — the
  // old copy said "no paid placement", so negations must not excuse it.
  { name: 'paid placement', re: /paid placement/i, negations: [] },
  { name: 'no favourites', re: /no favou?rites/i, negations: [] },
  { name: 'project fit', re: /project fit/i, negations: [] },
  { name: 'hand-pick', re: /hand[- ]?pick/i, negations: [] },
  { name: 'rank builders', re: /\brank(s|ing)? builders/i, negations: [] },
  { name: 'rank or recommend', re: /rank or recommend/i, negations: [] },
];

/** Strip HTML comments from a template. */
export function stripHtmlComments(html) {
  return html.replace(/<!--[\s\S]*?-->/g, '');
}

/**
 * Extract string-literal contents from TS source. Comments are excluded by
 * removing them first — a pragmatic stripper, good enough for copy files.
 */
export function extractStringLiterals(ts) {
  const noBlock = ts.replace(/\/\*[\s\S]*?\*\//g, '');
  const noLine = noBlock.replace(/(^|[^:])\/\/.*$/gm, '$1');
  const out = [];
  const re = /'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`/g;
  let m;
  while ((m = re.exec(noLine)) !== null) {
    out.push(m[0].slice(1, -1));
  }
  return out;
}

/** Scan one unit of user-facing text for banned phrases. Returns hits. */
export function scanUnit(unit, rel) {
  const hits = [];
  for (const { name, re, negations } of BANNED_PATTERNS) {
    const global = new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g');
    let m;
    while ((m = global.exec(unit)) !== null) {
      const before = unit.slice(Math.max(0, m.index - 40), m.index).toLowerCase();
      const negated = negations.some((n) => new RegExp(`\\b${n}\\b`).test(before));
      if (!negated) {
        const snippet = unit.slice(Math.max(0, m.index - 30), m.index + 40).replace(/\s+/g, ' ');
        hits.push(`${rel}: banned phrase "${name}" in user-facing copy: …${snippet}…`);
      }
    }
  }
  return hits;
}

// ── Single "Unlock" (issue #506, epic FE-3 / README DoD) ────────────────
// "Unlock" (any form: unlock, unlocks, unlocked, unlocking — case-insensitive)
// may appear in user-facing copy exactly once: the preview CTA,
// copy.report.unlockCta. Everything else says "Get your full report",
// "Show my report", "Revealed when you get your free report", etc.
export const UNLOCK_RE = /\bunlock/gi;
/** The single copy key allowed to carry "Unlock". */
export const UNLOCK_KEY = 'copy.report.unlockCta';

/**
 * Reduce an Angular template to its visible text: drop comments, tags
 * (attributes, bindings, class names like `cta unlock`), interpolations
 * (`{{ copy.unlockCta }}`) and control-flow headers (`@if (unlocked())`).
 */
export function templateText(html) {
  return stripHtmlComments(html)
    .replace(/<[^>]*>/g, ' ')
    .replace(/\{\{[\s\S]*?\}\}/g, ' ')
    .replace(/@\w+(?:\s+if)?\s*(\((?:[^()]|\([^()]*\))*\))?\s*\{?/g, ' ')
    .replace(/[{}]/g, ' ');
}

/** Every string value in a JSON tree, with its dotted path. */
export function jsonStrings(node, path = '', out = []) {
  if (typeof node === 'string') out.push({ path, text: node });
  else if (Array.isArray(node)) node.forEach((v, i) => jsonStrings(v, `${path}[${i}]`, out));
  else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) jsonStrings(v, path ? `${path}.${k}` : k, out);
  }
  return out;
}

/**
 * Count "Unlock" in user-facing copy. Rules:
 *  - app-config.defaults.ts: exactly ONE string literal carries it, and that
 *    literal must be the value of `unlockCta` inside the `report` block.
 *  - public/assets/config/app-config.json (runtime override of the same
 *    copy): only `copy.report.unlockCta` may carry it.
 *  - Templates and every other copy source: zero.
 * Returns failure strings (empty = clean).
 */
export function checkSingleUnlock(root = ROOT) {
  const failures = [];
  const webSrc = join(root, 'apps', 'web', 'src');
  const defaultsPath = join(webSrc, 'app', 'core', 'config', 'app-config.defaults.ts');

  for (const { path, kind } of copySources(root)) {
    let text;
    try {
      text = readFileSync(path, 'utf8');
    } catch {
      continue;
    }
    const rel = relative(root, path);
    if (path === defaultsPath) {
      const hits = extractStringLiterals(text).filter((u) => new RegExp(UNLOCK_RE.source, 'i').test(u));
      if (hits.length !== 1) {
        failures.push(
          `${rel}: "Unlock" must appear in exactly one copy string (${UNLOCK_KEY}); found ${hits.length}: ${hits.map((h) => JSON.stringify(h)).join(', ')}`,
        );
      }
      const reportBlock = text.match(/\n {4}report: \{([\s\S]*?)\n {4}\},/);
      const cta = reportBlock?.[1].match(/\n {6}unlockCta:\s*'([^']*)'/);
      if (!cta || !new RegExp(UNLOCK_RE.source, 'i').test(cta[1])) {
        failures.push(`${rel}: the one "Unlock" must be the preview CTA (${UNLOCK_KEY})`);
      }
      continue;
    }
    const units = kind === 'html' ? [templateText(text)] : extractStringLiterals(text);
    for (const unit of units) {
      if (new RegExp(UNLOCK_RE.source, 'i').test(unit)) {
        const i = unit.search(new RegExp(UNLOCK_RE.source, 'i'));
        const snippet = unit.slice(Math.max(0, i - 30), i + 40).replace(/\s+/g, ' ').trim();
        failures.push(`${rel}: "Unlock" outside the preview CTA (${UNLOCK_KEY}): …${snippet}…`);
      }
    }
  }

  const jsonPath = join(root, 'apps', 'web', 'public', 'assets', 'config', 'app-config.json');
  if (existsSync(jsonPath)) {
    const rel = relative(root, jsonPath);
    for (const { path, text } of jsonStrings(JSON.parse(readFileSync(jsonPath, 'utf8')))) {
      if (path !== UNLOCK_KEY && new RegExp(UNLOCK_RE.source, 'i').test(text)) {
        failures.push(`${rel}: "Unlock" outside the preview CTA at ${path}: ${JSON.stringify(text)}`);
      }
    }
  }
  return failures;
}

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out = walk(p, out);
    else out.push(p);
  }
  return out;
}

/** User-facing copy sources, relative to the repo root. */
function copySources(root) {
  const webSrc = join(root, 'apps', 'web', 'src');
  const apiSrc = join(root, 'apps', 'api', 'src');
  const files = [];
  try {
    for (const f of walk(join(webSrc, 'app'))) {
      if (extname(f) === '.html') files.push({ path: f, kind: 'html' });
    }
  } catch { /* no web app on this branch */ }
  files.push({ path: join(webSrc, 'app', 'core', 'config', 'app-config.defaults.ts'), kind: 'ts' });
  files.push({ path: join(webSrc, 'app', 'features', 'legal', 'privacy-page.component.ts'), kind: 'ts' });
  files.push({ path: join(webSrc, 'app', 'features', 'legal', 'terms-page.component.ts'), kind: 'ts' });
  files.push({ path: join(apiSrc, 'services', 'email', 'templates.ts'), kind: 'ts' });
  files.push({ path: join(apiSrc, 'lib', 'legal-copy.ts'), kind: 'ts' });
  return files;
}

/** Run the full check against a repo root. Returns { failures, notes }. */
export function checkBannedPhrases(root = ROOT) {
  const failures = [];
  const notes = [];

  for (const { path, kind } of copySources(root)) {
    let text;
    try {
      text = readFileSync(path, 'utf8');
    } catch {
      continue; // file doesn't exist on this branch — skip
    }
    const rel = relative(root, path);
    const units =
      kind === 'html' ? [stripHtmlComments(text)] : extractStringLiterals(text);
    for (const unit of units) {
      failures.push(...scanUnit(unit, rel));
    }
  }

  // Runtime config override of the same copy (#878): the served JSON must
  // not reintroduce a phrase the compiled defaults dropped.
  const configJson = join(root, 'apps', 'web', 'public', 'assets', 'config', 'app-config.json');
  if (existsSync(configJson)) {
    const rel = relative(root, configJson);
    for (const { path, text } of jsonStrings(JSON.parse(readFileSync(configJson, 'utf8')))) {
      failures.push(...scanUnit(text, `${rel} (${path})`));
    }
  }

  // ── Disclaimer presence ──
  const webSrc = join(root, 'apps', 'web', 'src');
  const apiSrc = join(root, 'apps', 'api', 'src');

  // 1. Report surface.
  const reportHtml = join(webSrc, 'app', 'features', 'report', 'report-page.component.html');
  if (existsSync(reportHtml)) {
    const html = readFileSync(reportHtml, 'utf8');
    if (!/narrativeDisclaimer|deterministic-note|deterministically/i.test(html)) {
      failures.push('report surface: no deterministic disclaimer found in report-page.component.html');
    }
    // 2. Print surface.
    if (/class="[^"]*deterministic-note[^"]*no-print|no-print[^"]*deterministic-note/.test(html)) {
      failures.push('print surface: disclaimer element carries .no-print');
    }
    const scssPath = join(webSrc, 'app', 'features', 'report', 'report-page.component.scss');
    if (existsSync(scssPath)) {
      const scss = readFileSync(scssPath, 'utf8');
      const printBlock = scss.match(/@media print\s*\{([\s\S]*)\}/);
      if (printBlock && /\.deterministic-note[^{]*\{[^}]*display\s*:\s*none/.test(printBlock[1])) {
        failures.push('print surface: .deterministic-note is display:none in @media print');
      }
    }
  }

  // 3. API surface.
  const contractsPath = join(root, 'packages', 'contracts', 'src', 'estimate.ts');
  const servicePath = join(apiSrc, 'services', 'estimate.service.ts');
  if (existsSync(contractsPath)) {
    const contracts = readFileSync(contractsPath, 'utf8');
    if (!contracts.includes(APPROVED_DISCLAIMER)) {
      failures.push('api surface: ESTIMATE_DISCLAIMER verbatim copy missing from packages/contracts/src/estimate.ts');
    }
    if (!/readonly disclaimer:\s*string/.test(contracts)) {
      failures.push('api surface: EstimateResponse.disclaimer field missing from contracts');
    }
  }
  if (existsSync(servicePath)) {
    const service = readFileSync(servicePath, 'utf8');
    if (!/disclaimer:\s*ESTIMATE_DISCLAIMER/.test(service)) {
      failures.push('api surface: estimate.service.ts does not set disclaimer: ESTIMATE_DISCLAIMER');
    }
  }

  // 4. MCP surface (#765 AC3) — every tool description carries the disclaimer.
  const mcpTools = [];
  for (const base of [join(root, 'packages', 'mcp'), join(apiSrc, 'mcp')]) {
    try {
      for (const f of walk(base)) {
        // Skip build output and dependencies — only source files carry copy.
        if (f.includes(`${sep}dist${sep}`) || f.includes(`${sep}node_modules${sep}`)) continue;
        if (extname(f) === '.ts' && !f.endsWith('.test.ts') && !f.endsWith('.spec.ts')) mcpTools.push(f);
      }
    } catch { /* dir doesn't exist yet */ }
  }
  if (mcpTools.length === 0) {
    notes.push('mcp surface: MCP server not merged yet — disclaimer check skipped until api-mcp/06 lands');
  } else {
    for (const f of mcpTools) {
      const src = readFileSync(f, 'utf8');
      if (
        /description\s*[:=]/.test(src) &&
        !src.includes('deterministically') &&
        !src.includes('ESTIMATE_DISCLAIMER')
      ) {
        failures.push(`mcp surface: ${relative(root, f)} has tool descriptions without the deterministic disclaimer`);
      }
    }
    failures.push(...checkMcpToolDefinitions(root));
  }

  // ── Single "Unlock" ──
  failures.push(...checkSingleUnlock(root));

  return { failures, notes };
}

/**
 * #765 AC3: per-tool disclaimer check on packages/mcp/src/tools.ts. The
 * disclaimer must come from the contracts' ESTIMATE_DISCLAIMER (single
 * source), and EVERY entry in TOOL_DEFINITIONS must append it to its
 * description — a file-level "contains 'deterministically'" match would
 * miss one tool silently dropping it.
 */
export function checkMcpToolDefinitions(root) {
  const toolsPath = join(root, 'packages', 'mcp', 'src', 'tools.ts');
  if (!existsSync(toolsPath)) return [];
  const rel = relative(root, toolsPath);
  const src = readFileSync(toolsPath, 'utf8');
  const failures = [];
  if (!/import\s*\{[^}]*\bESTIMATE_DISCLAIMER\b[^}]*\}\s*from\s*'@feasly\/contracts'/.test(src)) {
    failures.push(`mcp surface: ${rel} does not import ESTIMATE_DISCLAIMER from @feasly/contracts`);
  }
  const block = src.match(/TOOL_DEFINITIONS[^=]*=\s*\[([\s\S]*?)\n\];/);
  if (!block) {
    failures.push(`mcp surface: ${rel} has no TOOL_DEFINITIONS array`);
    return failures;
  }
  const entries = block[1].split(/\bname:\s*/).slice(1);
  if (entries.length === 0) {
    failures.push(`mcp surface: ${rel} TOOL_DEFINITIONS has no tools`);
  }
  for (const entry of entries) {
    const name = (entry.match(/^['"]([^'"]+)['"]/) ?? [, '?'])[1];
    if (!/\b(DETERMINISTIC_DISCLAIMER|ESTIMATE_DISCLAIMER)\b/.test(entry)) {
      failures.push(`mcp surface: tool ${name} in ${rel} has a description without the deterministic disclaimer`);
    }
  }
  return failures;
}

const isCli = process.argv[1] === fileURLToPath(import.meta.url);
if (isCli) {
  const { failures, notes } = checkBannedPhrases();
  for (const n of notes) console.log(`(${n})`);
  if (failures.length > 0) {
    console.error('');
    console.error(`BANNED-PHRASE / DISCLAIMER CHECK FAILED (${failures.length}):`);
    for (const f of failures) console.error(`  - ${f}`);
    console.error('');
    process.exit(1);
  }
  console.log('Banned-phrase + disclaimer check: clean. OK.');
}
