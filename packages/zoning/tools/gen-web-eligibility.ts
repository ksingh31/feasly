/**
 * Writes the web app's single-family eligibility lists from the zoning
 * catalogue (#911). The catalogue is the single source of truth; the web
 * app does not depend on this package, so it imports a generated data file
 * instead of keeping its own list. `test/eligibility-agreement.test.ts`
 * fails CI when the committed file is out of date.
 *
 * Usage (from the repo root): npm run gen:web-eligibility --workspace @feasly/zoning
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CALGARY_2026_08_04 } from '../src/data/calgary-2026-08-04';
import { singleDetachedEligibility } from '../src/eligibility';

export const WEB_ELIGIBILITY_FILE = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'web',
  'src',
  'app',
  'core',
  'config',
  'zoning-eligibility.generated.ts',
);

function list(codes: readonly string[]): string {
  return codes.map((c) => `      '${c}',`).join('\n');
}

/** The exact text of the generated file. */
export function renderWebEligibility(): string {
  const calgary = singleDetachedEligibility(CALGARY_2026_08_04);
  return `// GENERATED by packages/zoning/tools/gen-web-eligibility.ts — do not edit.
// Source: zoning catalogue ${CALGARY_2026_08_04.city} ${CALGARY_2026_08_04.effectiveDate} (${CALGARY_2026_08_04.bylaw}).
// Regenerate: npm run gen:web-eligibility --workspace @feasly/zoning

/**
 * Single-family eligibility derived from the zoning catalogue (#911).
 * \`quotable\`: districts with a cited single-detached use,
 * permitted or discretionary, plus site-specific Direct Control (fail-open).
 * \`discretionary\`: the subset where single-detached needs City approval.
 * \`rulesAsOf\`: the catalogue's effective date (ISO) — the "updated" stamp
 * for land use districts on How it works (#827). \`sourceUrl\`: the City
 * bylaw page the catalogue was read from (cited as the primary source).
 */
export const ZONING_ELIGIBILITY = {
  calgary: {
    rulesAsOf: '${CALGARY_2026_08_04.effectiveDate}',
    sourceUrl: '${CALGARY_2026_08_04.sourceUrl}',
    quotable: [
${list(calgary.quotable)}
    ],
    discretionary: [
${list(calgary.discretionary)}
    ],
  },
} as const;
`;
}

if (typeof require !== 'undefined' && typeof module !== 'undefined' && require.main === module) {
  writeFileSync(WEB_ELIGIBILITY_FILE, renderWebEligibility());
  console.log(`wrote ${WEB_ELIGIBILITY_FILE}`);
}
